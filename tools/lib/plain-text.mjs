/**
 * ふりがな（ruby）を落として、文字だけを取り出す。
 *
 * ── なぜ専用の関数が要るのか ────────────────────────
 *
 * 組み立ての中には「HTML から文字だけ取り出す」場所がいくつもある。
 * 目次のリンク、検索の索引、読むのにかかる時間、SNS カードの説明文。
 * どれも `replace(/<[^>]+>/g, '')` と書いてあった。タグを外すだけなので、
 * ふりがなは**中身が残る**。
 *
 *     <ruby>学年<rt>がくねん</rt></ruby>  →  学年がくねん
 *
 * 2026-08-30 に Qalc の使い方マニュアルで実際に出た。子ども向けアプリの
 * マニュアルは見出しにもふりがなを振るので、目次が
 * 「1ねん学がく年ねんから6ねん学がく年ねんまで」のような列になった。
 * 検索の索引にも同じ文字列が入り、当たったときに読めない見出しが出る。
 *
 * そのときは書式の側で「見出しにふりがなを使わない」と決めて逃げたが、
 * それは**いちばんふりがなが要る場所を諦める**ということだった。
 * 目次は、漢字が読めない子が最初に見るところである。
 *
 * ── 何をするか ────────────────────────────────
 *
 * `stripRuby()` は `<rt>` `<rp>` を**中身ごと**落とし、`<ruby>` の殻を外す。
 * 残るのは漢字そのもの（`学年`）。文字を数えたり検索に載せたりするのはこれ。
 *
 * `rubyOnly()` は逆に、ふりがなだけ残して他のタグを外す。
 * 目次のリンクに使う。`<a>` の中に `<a>` を入れられないので、
 * 見出しの中のリンクや `<code>` は外さなければならないが、
 * ふりがなは残したい、という一箇所のための関数である。
 *
 * どちらも入力は「組み上がった HTML」を想定している。実体参照
 * （`&amp;` など）は戻さない。目次はそのまま HTML に置くので戻すと壊れ、
 * 検索の索引は索引の側に戻す処理がある。
 */

/**
 * `<rt>…</rt>` と `<rp>…</rp>`。中身ごと落とす。
 *
 * ⚠️ 閉じタグは省略できる。`<ruby>学年<rt>がくねん</ruby>` は HTML として正しく、
 *    ブラウザはふりがなにするし、組み立て（article-md.mjs）もそのまま通す。
 *    `</rt>` を必ず求める形にしていると、ページは正しく出るのに、こちらだけが
 *    落とし損ねて目次と索引に「学年がくねん」が残る。
 *    そこで「次の ruby 系のタグ（または文字列の終わり）まで」を中身とみなし、
 *    自分の閉じタグは在れば食う。
 */
const READING_RE = /<(rt|rp)\b[^>]*>(?:(?!<\/?(?:rt|rp|ruby)\b)[\s\S])*(?:<\/\1\s*>)?/gi;

/** `<ruby>` `</ruby>` の殻。中身（漢字）は残す。 */
const RUBY_SHELL_RE = /<\/?ruby\b[^>]*>/gi;

/** ふりがな以外のタグ。 */
const OTHER_TAG_RE = /<(?!\/?(?:ruby|rt|rp)\b)[^>]+>/gi;

/** すべてのタグ。 */
const ANY_TAG_RE = /<[^>]+>/g;

/**
 * ふりがなを落として、漢字だけ残す。タグは外さない。
 *
 * @param {string} html
 * @returns {string}
 */
export const stripRuby = (html) =>
  String(html ?? '').replace(READING_RE, '').replace(RUBY_SHELL_RE, '');

/**
 * ふりがなを落としたうえで、タグを全部外す。
 * 文字を数える・検索に載せる・説明文にする、といった用途はこれ。
 *
 * @param {string} html
 * @returns {string}
 */
export const plainText = (html) => stripRuby(html).replace(ANY_TAG_RE, '');

/**
 * ふりがなだけ残して、ほかのタグを外す。目次のリンクの中身に使う。
 *
 * @param {string} html
 * @returns {string}
 */
export const rubyOnly = (html) => String(html ?? '').replace(OTHER_TAG_RE, '');
